-- Expose the fit analysis's REASONING to the candidate read model.
--
-- THE GAP. fit_analyses stores more than any candidate could see. technical_fit_components
-- holds six per-dimension scores, each with a rationale citing specific evidence from the JD
-- against the candidate's confirmed facts ("migrated 40 TB of warehouse tables", "cutting the
-- critical path from nine hours to seventy minutes"); risks holds the advisory concerns the
-- model raised (a shift pattern the JD specifies, work authorisation, an over-seniority
-- mismatch, a named tool absent from the facts). Both are generated by the model, paid for,
-- and stored -- and neither was projected out of these views, so the client could not select
-- them and the candidate never saw WHY a score was what it was.
--
-- WHY THE BASE VIEW FIRST. candidate_ranked_opportunities selects o.* FROM
-- candidate_opportunities, so the columns have to exist on the base view; the ranked view is
-- then recreated because its column list was expanded when it was created and would not
-- otherwise pick them up.
--
-- COLUMN ORDER IS LOAD-BEARING. CREATE OR REPLACE VIEW can only APPEND columns. Both new
-- columns therefore go at the END of each list, and the ranked view's 38 existing columns are
-- restated explicitly in their current order rather than re-selecting o.* -- which would insert
-- the two new base-view columns in the middle and fail with "cannot change name of view column".
--
-- DEPLOYMENT ORDERING -- MIGRATION FIRST, THEN CLIENT. This is the same requirement the
-- acceptance-evidence migration records: the client selects these columns, and against an
-- un-migrated database that select fails with 42703 and the feed renders its error state
-- instead of anything. No table and no row is modified here; only two view definitions are
-- replaced.

create or replace view public.candidate_opportunities
  with (security_invoker = on) as
  select
    v.id,
    v.raw_title,
    v.authoritative_url,
    v.country,
    v.region,
    v.city,
    v.remote_type,
    v.currency,
    v.salary_min,
    v.salary_max,
    v.salary_interval,
    v.salary_source,
    v.discovered_at,
    v.last_seen_at,
    v.expires_at,
    v.trust_status,

    c.displayed_name as company_name,
    c.domain         as company_domain,

    ap.gate_results     as plan_gate_results,
    latest.status       as attempt_status,

    fa.technical_fit_score,
    fa.practical_eligibility_score,
    fa.eligibility_capped,
    fa.hard_blockers,
    fa.missing_evidence,
    fa.top_reasons,
    fa.jd_text_available,

    fa.priority_score,
    fa.priority_uncapped_score,
    fa.priority_components,
    fa.priority_score_version,

    v.source_code,

    -- Appended: acceptance evidence for the SAME attempt as attempt_status.
    latest.accepted_evidence as attempt_accepted_evidence,

    -- Appended: the reasoning behind the score. risks is a string[] and is never null
    -- (default '[]'); technical_fit_components is a { dimension: { score, rationale } } object
    -- and IS null when there was no JD text to analyse.
    fa.risks,
    fa.technical_fit_components
  from public.vacancies v
  left join public.companies c on c.id = v.company_id
  left join public.application_plans ap on ap.vacancy_id = v.id
  left join lateral (
    select
      aa.status,
      exists (
        select 1
        from public.application_evidence e
        where e.application_attempt_id = aa.id
          and e.evidence_type = 'submission_confirmation'
          and jsonb_typeof(e.payload) = 'object'
          and e.payload <> '{}'::jsonb
          and (e.payload - 'adapterEvidenceType') <> '{}'::jsonb
      ) as accepted_evidence
    from public.application_attempts aa
    where aa.application_plan_id = ap.id
    order by aa.created_at desc
    limit 1
  ) latest on true
  left join public.fit_analyses fa on fa.vacancy_id = v.id
  where v.trust_status in ('VERIFIED', 'VERIFIED_INCOMPLETE', 'UNDER_REVIEW')
    and v.status = 'active';

comment on view public.candidate_opportunities is
  'Candidate-facing Opportunities read model. Exposes VERIFIED, VERIFIED_INCOMPLETE and UNDER_REVIEW active vacancies; UNDER_REVIEW rows must be rendered with an unverified-source warning. FLAGGED/BLOCKED/EXPIRED_REMOVED/ACTION_REQUIRED are deliberately excluded. security_invoker = on is load-bearing for candidate scoping. source_code is exposed for source attribution (Remotive requires it). attempt_accepted_evidence is computed for the SAME attempt as attempt_status and mirrors isTrustworthyAcceptanceEvidence(); it must never be treated as true when absent. risks and technical_fit_components carry the fit analysis reasoning; technical_fit_components is NULL (not empty) when no JD text was available.';

create or replace view public.candidate_ranked_opportunities
  with (security_invoker = on) as
with me as materialized (
  select auth.uid() as candidate_id
),
st as materialized (
  select public.candidate_ranking_state(me.candidate_id) as state from me
)
-- THE EXISTING 38 COLUMNS ARE RESTATED IN ORDER so the two appended columns land at the end.
select
  o.id,
  o.raw_title,
  o.authoritative_url,
  o.country,
  o.region,
  o.city,
  o.remote_type,
  o.currency,
  o.salary_min,
  o.salary_max,
  o.salary_interval,
  o.salary_source,
  o.discovered_at,
  o.last_seen_at,
  o.expires_at,
  o.trust_status,
  o.company_name,
  o.company_domain,
  o.plan_gate_results,
  o.attempt_status,
  o.technical_fit_score,
  o.practical_eligibility_score,
  o.eligibility_capped,
  o.hard_blockers,
  o.missing_evidence,
  o.top_reasons,
  o.jd_text_available,
  o.priority_score,
  o.priority_uncapped_score,
  o.priority_components,
  o.priority_score_version,
  o.source_code,
  o.attempt_accepted_evidence,
  me.candidate_id as ranking_candidate_id,
  st.state as ranking_state,
  public.candidate_ranking_identity(me.candidate_id) as ranking_identity,
  case
    when st.state = 'current'
      then public.candidate_ranked_matched_qualifiers(me.candidate_id, o.id)
    else null
  end as matched_qualifier_count,
  case
    when public.vacancy_evidence_is_current(o.id) then 'current'
    else 'pending'
  end as evidence_state,

  -- Appended, so the ranked read model carries the same reasoning as the base view.
  o.risks,
  o.technical_fit_components
from public.candidate_opportunities o
cross join me
cross join st
where
  st.state <> 'current'
  or not public.candidate_has_selected_roles(me.candidate_id)
  or exists (
    select 1
    from public.candidate_role_matches m
    join public.candidate_role_match_coverage c
      on c.candidate_id = m.candidate_id and c.published_generation = m.generation
    where m.candidate_id = me.candidate_id
      and m.vacancy_id = o.id
  );

comment on view public.candidate_ranked_opportunities is
  'Candidate-scoped ranked Opportunities read model, layered on candidate_opportunities. matched_qualifier_count is COUNT(DISTINCT qualifier) whose role this vacancy authoritatively matches, and is NULL unless the ranking state is current. evidence_state marks rows whose indexing is missing/stale. Applicability is recomputed in this query''s snapshot; a separate status read is informational only. risks and technical_fit_components are the fit analysis reasoning, appended after evidence_state so CREATE OR REPLACE could extend the column list.';
